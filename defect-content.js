function schemeSvg(key) {
  const sc = SCHEMES.find(s => s.id === key);
  if (!sc || !SHAPES[key]) return null;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 200" font-family="Arial, sans-serif">
<rect width="360" height="200" fill="#ffffff"/>${SHAPES[key]()}
<text x="180" y="182" text-anchor="middle" font-size="11" font-weight="bold" fill="#333">${esc(sc.label)}</text>
<text x="180" y="195" text-anchor="middle" font-size="9" fill="#666">${esc(sc.legend)}</text></svg>`;
}

